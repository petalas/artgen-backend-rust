//! Assemble the bundled shader sources. Each stage file in `src/shaders/` holds
//! only its own logic; the shared prelude is appended here: constants generated
//! from the Rust values the shaders must agree with, `common.wgsl`,
//! `changes.wgsl`, for the stages that read offspring change records
//! `offspring_changes.wgsl` and, for the tile group, `tiles.wgsl`. WGSL
//! module-scope declarations may follow their uses, so the stage body comes
//! first and naga's line numbers match its file. Shader variants never receive
//! the prelude.

use crate::gpu_evolver::changes::CHANGED_INDICES;
use crate::gpu_evolver::execution::{RASTER_WORK_HEADER_BYTES, TILE_OVERFLOW_ERROR};
use crate::settings::{POLYGON_CAPACITY, TILE_MAX_POLYS};

const COMMON: &str = include_str!("../../shaders/common.wgsl");
const CHANGES: &str = include_str!("../../shaders/changes.wgsl");
const OFFSPRING_CHANGES: &str = include_str!("../../shaders/offspring_changes.wgsl");
const TILES: &str = include_str!("../../shaders/tiles.wgsl");

const _: () = assert!(RASTER_WORK_HEADER_BYTES % 4 == 0 && RASTER_WORK_HEADER_BYTES >= 4);
const _: () = assert!(POLYGON_CAPACITY <= u32::MAX as usize);

/// A stage of the installed tile group. Its source depends on the raster tile.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TileStage {
    RasterizeError,
    BinPolygons,
    /// The separate worklist pass for binning variants that list no raster work.
    RasterWorklist,
    InitFramebuffers,
    UpdateFramebuffers,
}

impl TileStage {
    pub const ALL: [Self; 5] = [
        Self::RasterizeError,
        Self::BinPolygons,
        Self::RasterWorklist,
        Self::InitFramebuffers,
        Self::UpdateFramebuffers,
    ];

    fn file(self) -> (&'static str, &'static str) {
        match self {
            Self::RasterizeError => (
                "rasterize_error.wgsl",
                include_str!("../../shaders/rasterize_error.wgsl"),
            ),
            Self::BinPolygons => (
                "bin_polygons.wgsl",
                include_str!("../../shaders/bin_polygons.wgsl"),
            ),
            Self::RasterWorklist => (
                "raster_worklist.wgsl",
                include_str!("../../shaders/raster_worklist.wgsl"),
            ),
            Self::InitFramebuffers => (
                "init_framebuffers.wgsl",
                include_str!("../../shaders/init_framebuffers.wgsl"),
            ),
            Self::UpdateFramebuffers => (
                "update_framebuffers.wgsl",
                include_str!("../../shaders/update_framebuffers.wgsl"),
            ),
        }
    }
}

/// A bundled program. Only tile-group stages depend on the raster tile.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BundledShader {
    Mutate,
    Select,
    /// A tile-group stage for a raster tile of `[width, height]` pixels.
    Tile(TileStage, [u32; 2]),
}

impl BundledShader {
    /// The stage file name and its contents.
    #[must_use]
    pub fn file(self) -> (&'static str, &'static str) {
        match self {
            Self::Mutate => ("mutate.wgsl", include_str!("../../shaders/mutate.wgsl")),
            Self::Select => ("select.wgsl", include_str!("../../shaders/select.wgsl")),
            Self::Tile(stage, _) => stage.file(),
        }
    }

    /// Whether the stage reads offspring change records (binding the working
    /// and parent states that `offspring_changes.wgsl` reads).
    fn reads_offspring_changes(self) -> bool {
        match self {
            Self::Select
            | Self::Tile(
                TileStage::RasterizeError | TileStage::BinPolygons | TileStage::RasterWorklist,
                _,
            ) => true,
            Self::Mutate
            | Self::Tile(TileStage::InitFramebuffers | TileStage::UpdateFramebuffers, _) => false,
        }
    }
}

/// The complete WGSL of a bundled program: its stage file, then the prelude.
///
/// # Panics
/// Panics if a tile dimension is zero.
#[must_use]
pub fn bundled_shader_source(shader: BundledShader) -> String {
    let (_, body) = shader.file();
    let tile = match shader {
        BundledShader::Tile(_, tile) => Some(tile),
        BundledShader::Mutate | BundledShader::Select => None,
    };
    let prelude = COMMON.len() + CHANGES.len() + OFFSPRING_CHANGES.len() + TILES.len();
    let mut source = String::with_capacity(body.len() + prelude + 1024);
    source.push_str(body);
    push_part(&mut source, "generated by gpu_evolver::programs", &generated_constants(tile));
    push_part(&mut source, "common.wgsl", COMMON);
    push_part(&mut source, "changes.wgsl", CHANGES);
    if shader.reads_offspring_changes() {
        push_part(&mut source, "offspring_changes.wgsl", OFFSPRING_CHANGES);
    }
    if tile.is_some() {
        push_part(&mut source, "tiles.wgsl", TILES);
    }
    source
}

/// Append one prelude part under a header naming it, so a compiler error past
/// the stage body can be traced to its file.
fn push_part(source: &mut String, name: &str, part: &str) {
    if !source.ends_with('\n') {
        source.push('\n');
    }
    source.push_str("\n// ---- ");
    source.push_str(name);
    source.push_str(" ----\n");
    source.push_str(part);
}

/// Constants shared with Rust. The tile size uses the variants' marker form
/// (`const TILE_W: u32 = 16;`), so a 16x16 source emitted for benchmarks
/// installs as a shader variant and specializes like a historical source.
fn generated_constants(tile: Option<[u32; 2]>) -> String {
    let common = format!(
        "const POLYGON_CAPACITY: u32 = {POLYGON_CAPACITY}u; // settings::POLYGON_CAPACITY\n\
         const TILE_MAX_POLYS: u32 = {TILE_MAX_POLYS}u; // settings::TILE_MAX_POLYS\n\
         const CHANGED_INDICES: u32 = {CHANGED_INDICES}u; // changes::CHANGED_INDICES\n\
         const TILE_OVERFLOW_ERROR: u32 = {TILE_OVERFLOW_ERROR}u; // execution::TILE_OVERFLOW_ERROR\n"
    );
    let Some([width, height]) = tile else {
        return common;
    };
    assert!(width > 0 && height > 0, "raster tile {width}x{height} must be nonempty");
    let entries = RASTER_WORK_HEADER_BYTES / 4;
    format!(
        "{common}\
         const TILE_W: u32 = {width};\n\
         const TILE_H: u32 = {height};\n\
         // raster_work words: the entry count, then entries (execution::RASTER_WORK_HEADER_BYTES)\n\
         const WORK_COUNT: u32 = 0u;\n\
         const WORK_ENTRIES: u32 = {entries}u;\n"
    )
}

#[cfg(test)]
mod tests {
    use wgpu::naga::{self, back::spv, valid, Module, TypeInner};

    use super::{bundled_shader_source, BundledShader, TileStage};
    use crate::gpu_evolver::buffers::{ControlFlags, GpuDrawingState, GpuParams, GpuPolygon};
    use crate::gpu_evolver::changes::GpuChainChange;

    // The supported raster tiles; see rasterize_error.wgsl.
    const TILES: [[u32; 2]; 5] = [[32, 16], [16, 16], [32, 8], [16, 8], [8, 8]];

    fn all_shaders() -> Vec<BundledShader> {
        let mut shaders = vec![BundledShader::Mutate, BundledShader::Select];
        for stage in TileStage::ALL {
            shaders.extend(TILES.map(|tile| BundledShader::Tile(stage, tile)));
        }
        shaders
    }

    fn validated(shader: BundledShader) -> (Module, valid::ModuleInfo) {
        let source = bundled_shader_source(shader);
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|error| panic!("{shader:?}: {}", error.emit_to_string(&source)));
        let info = valid::Validator::new(valid::ValidationFlags::all(), valid::Capabilities::all())
            .validate(&module)
            .unwrap_or_else(|error| panic!("{shader:?}: {}", error.emit_to_string(&source)));
        (module, info)
    }

    /// Every assembled program validates and passes through the SPIR-V writer,
    /// which can reject what validation accepts (see docs/LEARNINGS.md).
    #[test]
    fn every_bundled_shader_validates_and_writes_spirv_at_every_supported_tile() {
        for shader in all_shaders() {
            let (module, info) = validated(shader);
            let entry_point = if shader == BundledShader::Select { "select_main" } else { "main" };
            let options = spv::Options { lang_version: (1, 3), ..spv::Options::default() };
            let pipeline = spv::PipelineOptions {
                shader_stage: naga::ShaderStage::Compute,
                entry_point: entry_point.into(),
            };
            spv::write_vec(&module, &info, &options, Some(&pipeline))
                .unwrap_or_else(|error| panic!("{shader:?}: {error}"));
        }
    }

    /// Bytes of workgroup memory a program declares, as naga lays it out.
    fn workgroup_bytes(module: &Module) -> u32 {
        let mut layouter = naga::proc::Layouter::default();
        layouter.update(module.to_ctx()).expect("layout");
        module
            .global_variables
            .iter()
            .filter(|(_, global)| global.space == naga::AddressSpace::WorkGroup)
            .map(|(_, global)| layouter[global.ty].size)
            .sum()
    }

    /// Every program fits the engine's request. Mutate keeps no copy of a
    /// parent there: only its crossover keep bits, 4 bytes per 32 polygon
    /// slots, grow with the polygon capacity.
    #[test]
    fn every_bundled_shader_fits_the_requested_workgroup_memory() {
        use crate::gpu_evolver::execution::WORKGROUP_STORAGE_BYTES;
        use crate::settings::POLYGON_CAPACITY;
        let requested = WORKGROUP_STORAGE_BYTES;
        for shader in all_shaders() {
            let (module, _) = validated(shader);
            let bytes = workgroup_bytes(&module);
            assert!(bytes <= requested, "{shader:?}: {bytes} bytes");
        }
        let (mutate, _) = validated(BundledShader::Mutate);
        let keep_bits = u32::try_from(POLYGON_CAPACITY.div_ceil(32) * 4).unwrap();
        assert!(workgroup_bytes(&mutate) < keep_bits + 256, "{}", workgroup_bytes(&mutate));
    }

    #[test]
    fn stage_line_numbers_are_unchanged_by_the_prelude() {
        for shader in all_shaders() {
            let (_, body) = shader.file();
            assert!(bundled_shader_source(shader).starts_with(body), "{shader:?}");
        }
    }

    /// (size, [(member name, offset)]) of a named struct, as naga lays it out.
    fn reflected(module: &Module, name: &str) -> (u32, Vec<(String, u32)>) {
        let (_, ty) = module
            .types
            .iter()
            .find(|(_, ty)| ty.name.as_deref() == Some(name))
            .unwrap_or_else(|| panic!("struct {name} is not declared"));
        let TypeInner::Struct { members, span } = &ty.inner else {
            panic!("{name} is not a struct");
        };
        let members = members
            .iter()
            .map(|member| (member.name.clone().unwrap(), member.offset))
            .collect();
        (*span, members)
    }

    /// Rust field names and offsets, in declaration order.
    macro_rules! rust_layout {
        ($ty:ty { $($field:ident),* $(,)? }) => {
            (
                std::mem::size_of::<$ty>(),
                vec![$((stringify!($field), std::mem::offset_of!($ty, $field))),*],
            )
        };
    }

    /// Compare a WGSL struct with its Rust mirror. `rename` maps a WGSL member
    /// to its Rust field and the byte offset within that field.
    fn assert_layout(
        module: &Module,
        name: &str,
        rust: &(usize, Vec<(&str, usize)>),
        rename: impl Fn(&str) -> (String, usize),
    ) {
        let (size, members) = reflected(module, name);
        assert_eq!(size as usize, rust.0, "{name} size");
        for (member, offset) in &members {
            let (field, within) = rename(member);
            let expected = rust
                .1
                .iter()
                .find(|(rust_field, _)| *rust_field == field)
                .unwrap_or_else(|| panic!("{name}.{member} has no Rust field {field}"));
            assert_eq!(*offset as usize, expected.1 + within, "{name}.{member}");
        }
        // Every Rust field is mirrored by at least one WGSL member.
        for (field, _) in &rust.1 {
            assert!(
                members.iter().any(|(member, _)| rename(member).0 == *field),
                "{name} does not mirror Rust field {field}"
            );
        }
    }

    #[test]
    fn shader_struct_layouts_match_the_rust_buffers() {
        let (module, _) = validated(BundledShader::Mutate);
        let same = |member: &str| (member.to_owned(), 0);
        assert_layout(&module, "Polygon", &rust_layout!(GpuPolygon { data }), same);
        assert_layout(
            &module,
            "DrawingState",
            &rust_layout!(GpuDrawingState {
                polygon_count, fitness_bits, mutation_scale_bits, stagnation_counter,
                rng_state, polygons,
            }),
            |member| match member {
                "mutation_scale" => ("mutation_scale_bits".into(), 0),
                _ => same(member),
            },
        );
        assert_layout(
            &module,
            "Params",
            &rust_layout!(GpuParams {
                image_width, image_height, max_polygons, min_polygons,
                max_error_per_pixel, per_point_penalty, iteration_number, _pad0,
                add_polygon_prob, remove_polygon_prob, reorder_polygon_prob, offset_polygon_prob,
                move_point_prob, micro_adjust_prob, change_color_prob, adjust_brightness_prob,
                adjust_saturation_prob, move_point_max_delta, micro_adjust_delta,
                new_point_max_distance,
                offset_polygon_magnitude, min_alpha_norm, max_alpha_norm, crossover_prob,
                spatial_crossover_weight, tournament_size, incremental_eval, tile_culling,
                chain_count_param, single_mutation_mode, lambda, adaptive_mutation,
                scale_polygon_prob, rotate_polygon_prob, adjacent_swap_prob, merge_polygon_prob,
                clone_polygon_prob, medium_move_prob, medium_move_delta, swap_colors_prob,
                merge_centroid_threshold, merge_color_threshold, _pad2, _pad3,
                _reserved,
            }),
            |member| match member {
                // Shaders ignore these words.
                "_pad_ie" => ("incremental_eval".into(), 0),
                "_pad_tc" => ("tile_culling".into(), 0),
                _ => match member.strip_prefix("_reserved") {
                    Some(k) => ("_reserved".into(), 16 * k.parse::<usize>().unwrap()),
                    None => same(member),
                },
            },
        );
        let (select, _) = validated(BundledShader::Select);
        assert_layout(
            &select,
            "ControlFlags",
            &rust_layout!(ControlFlags { new_best_found, best_chain_id, best_fitness_bits, _pad }),
            same,
        );
        assert_layout(
            &select,
            "ChainChange",
            &rust_layout!(GpuChainChange { changed, parent_mask, _pad, parents }),
            same,
        );
    }
}
